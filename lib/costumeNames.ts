const NUMBERED: Record<string, { ru: string; en: string }> = {
  Parūka: { ru: "Парик", en: "Wig" },
  Maska: { ru: "Маска", en: "Mask" },
};

/** Kostīma nosaukums izvēlētajā valodā (pēc vārdnīcas). */
export function translateCostumeName(title: string, lang: Lang): string {
  if (lang === "lv" || !title) return title;
  const clean = title.trim();

  const exact = NAMES[clean];
  if (exact) return exact[lang];

  // "Zaķis (2)" -> "Заяц (2)"
  const numbered = clean.match(/^(.*?)\s*\((\d+)\)$/);
  if (numbered && NAMES[numbered[1]]) return `${NAMES[numbered[1]][lang]} (${numbered[2]})`;

  // "Parūka 5", "Maska (3)"
  const series = clean.match(/^(\p{L}+)\s*\(?(\d+)\)?$/u);
  if (series && NUMBERED[series[1]]) return `${NUMBERED[series[1]][lang]} ${series[2]}`;

  return title;
}

/** Izmēra/cenas teksts izvēlētajā valodā ("S-XL līdz 185cm" -> "S-XL до 185 см"). */
export function translateCostumeDetail(text: string, lang: Lang): string {
  if (lang === "lv" || !text) return text;
  // Vārda robežas ar burtiem ā, ē, ī... (parastais \b tos neatpazīst)
  const w = (source: string) => new RegExp(`(?<!\\p{L})${source}(?!\\p{L})`, "giu");
  const words: [RegExp, { ru: string; en: string }][] = [
    [w("Derēs līdz"), { ru: "Подойдёт до", en: "Fits up to" }],
    [w("līdz\\s+(\\d+)\\s+diennaktīm"), { ru: "до $1 суток", en: "up to $1 days" }],
    [w("līdz"), { ru: "до", en: "up to" }],
    [w("jeb"), { ru: "или", en: "or" }],
    [w("pieaugušo kostīmi"), { ru: "взрослых костюма", en: "adult costumes" }],
    [w("bērnu kostīms"), { ru: "детский костюм", en: "kids' costume" }],
    [w("gadi"), { ru: "лет", en: "years" }],
    [w("diennakts"), { ru: "сутки", en: "day" }],
    [w("dienā"), { ru: "в день", en: "per day" }],
    [w("One size"), { ru: "Один размер", en: "One size" }],
    [/(\d)\s*cm(?!\p{L})/giu, { ru: "$1 см", en: "$1 cm" }],
  ];
  return words.reduce((result, [pattern, value]) => result.replace(pattern, value[lang]), text);
}
